import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import { catalogPrompt } from "../src/features/agent/catalog-prompt.ts";

/**
 * Writes the catalog prompt into `services/agent/catalog-prompt.generated.ts`, committed, so a
 * route handler imports only a string and never `react-lang` (P9). Run it through
 * `nx run @genie/core:agent-prompt`; `catalog.test.ts` fails when the committed prompt drifts from
 * the catalog.
 */
const output = resolve(
  import.meta.dirname,
  "../src/services/agent/catalog-prompt.generated.ts"
);

const document = `// Generated by \`packages/core/tools/emit-agent-prompt.ts\`. Do not edit; run the tool after a catalog change.

export const CATALOG_PROMPT: string = ${JSON.stringify(catalogPrompt())};
`;

await writeFile(output, document, "utf8");

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

import {
  agentContract,
  auditContract,
  brandingContract,
  categoriesContract,
  groupsContract,
  modulesContract,
  peopleContract,
  rolesContract,
  settingsContract,
} from "@genie/core";
import {
  readModuleInventory,
  type ModuleInventoryEntry,
} from "@genie/generators";
import { OpenAPIGenerator } from "@orpc/openapi";
import { ZodToJsonSchemaConverter } from "@orpc/zod/zod4";

/**
 * The OpenAPI build script of ADR 0011, decision 4: one document, generated from
 * core's administration contracts plus every module in `packages/modules/*`
 * in id order, checked in, and refused by CI when it drifts. This is the fourth
 * and last place allowed to import `@orpc/*` (the confinement allow-list in
 * `packages/config/src/oxlint/boundaries.ts`), so a later oRPC upgrade touches
 * core's RPC entry, the app's oRPC folder, the `/api/rpc` route and this file
 * alone.
 *
 * Spec only: no `OpenAPIHandler` is mounted. The document is a deliberate
 * exception to ADR 0008's uncommitted-generated-output rule, so every API change
 * shows up in code review; `--check` turns a stale document into a failed CI run.
 *
 *   node tools/generate-openapi.ts          # write apps/genie/openapi.json
 *   node tools/generate-openapi.ts --check  # fail when the checked-in file differs
 */
const CHECKOUT_ROOT = resolve(import.meta.dirname, "../../..");

/** The checked-in document, repository-relative. */
export const OPENAPI_PATH = "apps/genie/openapi.json";

/** Core's administration areas, in id order, as the decision record lists them (decision 7). */
const CORE_AREA_CONTRACTS = {
  agent: agentContract,
  audit: auditContract,
  branding: brandingContract,
  categories: categoriesContract,
  groups: groupsContract,
  modules: modulesContract,
  people: peopleContract,
  roles: rolesContract,
  settings: settingsContract,
};

/** The module generator's fixed contract export name: `contract-data` becomes `contractDataContract`. */
function contractExportName(moduleId: string): string {
  const camel = moduleId.replace(/-([a-z0-9])/g, (_, char: string) =>
    char.toUpperCase()
  );

  return `${camel}Contract`;
}

/**
 * Imports one module's contract by file path, never by package name: the app
 * declares only the modules its own image selects, and this document covers every
 * module in the workspace. The `./contract` export is `./src/contract.ts` for
 * every module (enforced by `moduleProjectNamingError`), and that file is
 * browser-safe, so importing it pulls no server code.
 */
async function loadModuleContract(entry: ModuleInventoryEntry) {
  const contractPath = resolve(
    CHECKOUT_ROOT,
    entry.packageRoot,
    "src/contract.ts"
  );

  const loaded = await import(pathToFileURL(contractPath).href);
  const exportName = contractExportName(entry.id);
  const contract = loaded[exportName];

  if (contract === undefined) {
    throw new Error(
      `${entry.packageRoot}/src/contract.ts exports no ${exportName}. A module publishes its contract under the name the module generator gives it (ADR 0011).`
    );
  }

  return [entry.id, contract] as const;
}

/** The composed contract: core's areas, then every module in id order. */
async function composeContract() {
  const modules = readModuleInventory(CHECKOUT_ROOT).toSorted((left, right) =>
    left.id < right.id ? -1 : 1
  );

  const contract = new Map(Object.entries(CORE_AREA_CONTRACTS));
  const moduleContracts = await Promise.all(modules.map(loadModuleContract));

  for (const [id, moduleContract] of moduleContracts) {
    if (contract.has(id)) {
      throw new Error(
        `Module "${id}" collides with a core area id. Core reserves ${Object.keys(CORE_AREA_CONTRACTS).join(", ")} (ADR 0011).`
      );
    }

    contract.set(id, moduleContract);
  }

  return Object.fromEntries(contract);
}

/** The generated document as a value, for the behavior test to inspect. */
export async function openApiDocument() {
  const generator = new OpenAPIGenerator({
    schemaConverters: [new ZodToJsonSchemaConverter()],
  });

  return generator.generate(await composeContract(), {
    info: {
      title: "Genie Ops Center API",
      version: "0.0.0",
      description:
        "The composed RPC contract as OpenAPI: core's agent, audit, branding, categories, groups, modules, people, roles and settings areas, then every module in packages/modules in id order. Generated by tools/generate-openapi.ts and checked in, so every API change shows up in review; do not edit by hand (ADR 0011, decision 4). Responses declared with z.custom are unconstrained.",
    },
  });
}

/** The exact bytes written to disk and compared by the check target. */
export async function openApiDocumentText(): Promise<string> {
  return `${JSON.stringify(await openApiDocument(), undefined, 2)}\n`;
}

/**
 * The reason the checked-in document is stale, or `undefined` when it matches.
 *
 * The comparison is the whole document text, not a parsed subset, so any drift
 * fails CI: a changed path, a changed method, a changed input schema, or a
 * reordered one. The generator is deterministic given the composed contract, so
 * an exact comparison needs no header field to parse.
 */
export async function openApiMismatch(): Promise<string | undefined> {
  const target = resolve(CHECKOUT_ROOT, OPENAPI_PATH);

  if (!existsSync(target)) {
    return `There is no checked-in OpenAPI document at ${OPENAPI_PATH}. Run "pnpm nx run @genie/app:generate-openapi" and commit the result.`;
  }

  if (readFileSync(target, "utf8") === (await openApiDocumentText())) {
    return undefined;
  }

  return `${OPENAPI_PATH} is not the document the composed contract generates. A contract change is not reflected in the checked-in file; run "pnpm nx run @genie/app:generate-openapi" and commit the result (ADR 0011, decision 4).`;
}

/** Writes the generated document to the checked-in path. */
export async function writeOpenApiDocument(): Promise<string> {
  writeFileSync(
    resolve(CHECKOUT_ROOT, OPENAPI_PATH),
    await openApiDocumentText(),
    "utf8"
  );

  return `wrote ${OPENAPI_PATH}`;
}

async function main(): Promise<void> {
  if (process.argv.slice(2).includes("--check")) {
    const problem = await openApiMismatch();

    if (problem !== undefined) {
      process.stderr.write(`${problem}\n`);
      process.exitCode = 1;
    }

    return;
  }

  process.stdout.write(`${await writeOpenApiDocument()}\n`);
}

if (
  process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  await main();
}
